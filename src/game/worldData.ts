/**
 * Exact 5x5 City Grid Layout matching user specification:
 * 5 rows x 5 columns. Block pitch = 32m (24m lot + 8m street).
 */
export const GRID_SIZE = 5;
export const BLOCK_SIZE = 24;
export const STREET_WIDTH = 8;
export const CELL_PITCH = BLOCK_SIZE + STREET_WIDTH; // 32m center-to-center

export function gridToWorld(row: number, col: number): { x: number; z: number } {
  const offset = (GRID_SIZE - 1) / 2; // 2
  return {
    x: (col - offset) * CELL_PITCH,
    z: (row - offset) * CELL_PITCH,
  };
}

